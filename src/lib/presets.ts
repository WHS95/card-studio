export const emptyBrief = (): Brief => ({ industry: "", about: "", audience: "", goals: [], tone: "", keywords: [], banned: [], hashtags: [], cta: "", link: "", references: [] });

/** 브리프가 얼마나 채워졌는지 (시작 체크리스트용) */
export function briefDone(b: Brief | undefined) {
  if (!b) return false;
  return !!(b.about.trim() && b.audience.trim() && b.tone.trim());
}
